import { defaultLocale, locales, type Level, type Locale } from "@/lib/types";

export function isLocale(value: string): value is Locale {
  return (locales as readonly string[]).includes(value);
}

/** Prefixes an internal path with the locale: ("/courses/python", "en") -> "/en/courses/python". */
export function localePath(locale: Locale, path = "/"): string {
  const clean = path === "/" ? "" : path;
  return `/${locale}${clean}`;
}

/** Same page in another language. */
export function switchLocalePath(pathname: string, target: Locale): string {
  const parts = pathname.split("/");
  if (isLocale(parts[1] ?? "")) parts[1] = target;
  else parts.splice(1, 0, target);
  return parts.join("/") || `/${target}`;
}

