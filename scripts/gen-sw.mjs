/**
 * Generates the service worker (out/sw.js) after `next build` (static export).
 *
 * It walks the exported `out/` folder and injects:
 *   - CRITICAL: the app shell (opens offline immediately after first load)
 *   - MANIFEST: every exported file, cached in the background so ALL lessons and
 *     practice pages work with no internet — the core requirement for studying
 *     offline during power / network cuts.
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, dirname, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "out");
const basePath = (process.env.NEXT_PUBLIC_BASE_PATH ?? "").replace(/\/$/, "");

function walk(dir) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(full));
    else files.push(full);
  }
  return files;
}

const all = walk(outDir)
  .filter((f) => !f.endsWith(".map") && !f.endsWith(sep + "sw.js"))
  .map((f) => `${basePath}/${relative(outDir, f).split(sep).join("/")}`);

// A clean URL for each exported directory index, so "/fr/courses/python/" resolves offline.
const urls = new Set();
for (const f of all) {
  urls.add(f);
  if (f.endsWith("/index.html")) urls.add(f.slice(0, -"index.html".length)); // ".../"
}
const manifest = [...urls].sort();

// Version = hash of the manifest, so a new build busts the old cache.
const version = createHash("sha256").update(manifest.join("\n")).digest("hex").slice(0, 12);

const critical = manifest.filter(
  (u) =>
    u.startsWith(`${basePath}/_next/static/`) ||
    u.startsWith(`${basePath}/icons/`) ||
    u.startsWith(`${basePath}/search/`) ||
    u.startsWith(`${basePath}/certificat-template/`) ||
    u === `${basePath}/manifest.webmanifest` ||
    u === `${basePath}/fr/` ||
    u === `${basePath}/en/`,
);

const totalBytes = walk(outDir).reduce((n, f) => n + statSync(f).size, 0);

const sw = `/* DevSecOps App service worker - generated by scripts/gen-sw.mjs. Do not edit by hand. */
const VERSION = ${JSON.stringify(version)};
const CACHE = "devsecops-app-" + VERSION;
const BASE = ${JSON.stringify(basePath)};
const OFFLINE_FALLBACK = BASE + "/fr/";
const CRITICAL = ${JSON.stringify(critical)};
const MANIFEST = ${JSON.stringify(manifest)};

// Cross-origin runtimes used by the "Try it Yourself" playground (Pyodide, SQLite, Monaco).
const RUNTIME_HOSTS = ["cdn.jsdelivr.net", "cdnjs.cloudflare.com"];

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      // critical shell first, so the app opens offline right away
      await cache.addAll(CRITICAL.map((u) => new Request(u, { cache: "reload" }))).catch(() => {});
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.filter((k) => k !== CACHE && k.startsWith("devsecops-app-")).map((k) => caches.delete(k)));
      await self.clients.claim();
      // then pull the rest of the site into the cache in the background, for full offline use
      precacheAll();
    })(),
  );
});

async function precacheAll() {
  const cache = await caches.open(CACHE);
  const pending = MANIFEST.slice();
  const WORKERS = 6;
  await Promise.all(
    Array.from({ length: WORKERS }, async () => {
      while (pending.length) {
        const url = pending.pop();
        if (await cache.match(url)) continue;
        try {
          const res = await fetch(url, { cache: "no-cache" });
          if (res.ok) await cache.put(url, res);
        } catch {
          /* offline: will be retried on a later activate */
        }
      }
    }),
  );
}

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
  if (event.data && event.data.type === "CACHE_ALL") event.waitUntil(precacheAll());
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  const url = new URL(request.url);

  // playground runtimes: cache-first, refresh in the background (stale-while-revalidate)
  if (RUNTIME_HOSTS.includes(url.hostname)) {
    event.respondWith(staleWhileRevalidate(request));
    return;
  }

  if (url.origin !== self.location.origin) return;

  // page navigations: network-first (to catch updates) then cache then home fallback
  if (request.mode === "navigate") {
    event.respondWith(
      (async () => {
        try {
          const fresh = await fetch(request);
          const cache = await caches.open(CACHE);
          cache.put(request, fresh.clone());
          return fresh;
        } catch {
          const cache = await caches.open(CACHE);
          return (await cache.match(request)) || (await cache.match(url.pathname)) || (await cache.match(OFFLINE_FALLBACK)) || Response.error();
        }
      })(),
    );
    return;
  }

  // same-origin assets: cache-first
  event.respondWith(
    (async () => {
      const cached = await caches.match(request);
      if (cached) return cached;
      try {
        const res = await fetch(request);
        if (res.ok && res.type === "basic") {
          const cache = await caches.open(CACHE);
          cache.put(request, res.clone());
        }
        return res;
      } catch {
        return Response.error();
      }
    })(),
  );
});

async function staleWhileRevalidate(request) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(request);
  const network = fetch(request)
    .then((res) => {
      if (res.ok) cache.put(request, res.clone());
      return res;
    })
    .catch(() => cached);
  return cached || network;
}
`;

writeFileSync(join(outDir, "sw.js"), sw);
console.log(`✔ service worker written: ${manifest.length} URLs precached, version ${version} (~${(totalBytes / 1e6).toFixed(1)} MB offline)`);
